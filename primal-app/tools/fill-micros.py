"""Completes missing micronutrients of PRIMAL foods (run after tools/import-ciqual.py).

1. Official values first: a PRIMAL food that has a Ciqual code gets, for each
   nutrient it lacks, the value of the SAME food in Ciqual 2025 (never overwrites).
2. Estimates for what is still missing: median of the foods of the same Ciqual
   sub-sub-group (≥ 3 foods measured), else of the same sub-group (≥ 5).
   Estimated nutrients are listed per food, so the app can flag them.

Output: src/lib/ciqualFill.ts  { code: { exact: {...}, estimated: {...} } }
Source: Table Ciqual 2025 (ANSES), Licence Ouverte Etalab 2.0.
"""
import importlib.util, json, re, statistics, sys
from collections import defaultdict
import openpyxl

spec = importlib.util.spec_from_file_location('ic', 'tools/import-ciqual.py'); ic = importlib.util.module_from_spec(spec); spec.loader.exec_module(ic)
OUT = 'src/lib/ciqualFill.ts'
FILL_KEYS = ['omega3'] + ic.MICROS

def values_of(r):
    v = {k: ic.num(r[i]) for k, i in ic.COLS.items()}
    for k, i in ic.FALLBACK.items():
        if v[k] is None: v[k] = ic.num(r[i])
    o3 = [ic.num(r[i]) for i in ic.OMEGA3]
    v['omega3'] = round(sum(o3), 4) if all(x is not None for x in o3) else None
    return v

def present_keys(path, code_re):
    """code → set of nutrient keys already filled in a PRIMAL source file."""
    text = open(path, encoding='utf-8').read(); out = {}
    for m in re.finditer(code_re, text):
        out[int(m.group('code'))] = set(re.findall(r'\b(' + '|'.join(FILL_KEYS + ['vitA']) + r'): ', m.group('body')))
    return out

def main():
    rows = list(openpyxl.load_workbook(ic.SRC, read_only=True)['composition nutritionnelle'].iter_rows(values_only=True))[1:]
    data = {}; group = {}
    by_subsub = defaultdict(list); by_sub = defaultdict(list)
    for r in rows:
        if not r[6] or str(r[1]).startswith('00'): continue
        code = int(r[6]); v = values_of(r); data[code] = v
        group[code] = (str(r[1]), ic.clean(r[5]))
        by_subsub[group[code]].append(code); by_sub[str(r[1])].append(code)

    def estimate(code, key):
        for pool, need in ((by_subsub[group[code]], 3), (by_sub[group[code][0]], 5)):
            vals = [data[c][key] for c in pool if c != code and data[c][key] is not None]
            if len(vals) >= need: return round(statistics.median(vals), 4)
        return None

    # Which keys each PRIMAL food already has.
    core = present_keys('src/lib/foodCore.ts', r"alim_code: (?P<code>\d+)[^\n]*?values: \{(?P<body>[^}]*)\}")
    c25 = present_keys('src/lib/ciqual2025.ts', r"alim_code: (?P<code>\d+), (?P<body>[^\n]*)")
    full_text = open('src/lib/ciqualFull.ts', encoding='utf-8').read()
    keys_full = json.loads(re.search(r'CIQUAL_FULL_KEYS: NutrientKey\[\] = (\[.*?\]);', full_text).group(1))
    full = {}
    for m in re.finditer(r'^  \[(\d+), "(?:[^"\\]|\\.)*", "\w+", \d, (.*)\],$', full_text, re.M):
        vals = [x.strip() for x in m.group(2).split(',')]
        full[int(m.group(1))] = {k for k, x in zip(keys_full, vals) if x != 'null'}
    # ciqual2025.ts uses French field names: map the ones we fill.
    FR = {'calcium': 'calcium_mg', 'copper': 'cuivre_mg', 'iron': 'fer_mg', 'iodine': 'iode_ug', 'magnesium': 'magnesium_mg', 'manganese': 'manganese_mg', 'phosphorus': 'phosphore_mg', 'potassium': 'potassium_mg', 'selenium': 'selenium_ug', 'sodium': 'sodium_mg', 'zinc': 'zinc_mg', 'vitA': 'vitA_ug', 'vitD': 'vitD_ug', 'vitE': 'vitE_mg', 'vitK': 'vitK1_ug', 'vitC': 'vitC_mg', 'vitB1': 'vitB1_mg', 'vitB2': 'vitB2_mg', 'vitB3': 'vitB3_mg', 'vitB5': 'vitB5_mg', 'vitB6': 'vitB6_mg', 'vitB9': 'vitB9_ug', 'vitB12': 'vitB12_ug'}
    text25 = open('src/lib/ciqual2025.ts', encoding='utf-8').read()
    for m in re.finditer(r"alim_code: (\d+), ([^\n]*)", text25):
        body = m.group(2); c25[int(m.group(1))] = {k for k, fr in FR.items() if re.search(r'\b' + fr + r': (?!null)', body)}
    targets = {}
    for src in (full, c25, core):
        for code, keys in src.items(): targets[code] = targets.get(code, set()) | keys
    fill = {}; n_exact = n_est = 0; still = 0
    for code, have in targets.items():
        if code not in data: continue
        exact = {}; est = {}
        for k in FILL_KEYS:
            if k in have: continue
            if code in core and data[code][k] is not None: exact[k] = round(data[code][k], 4)
            else:
                e = estimate(code, k)
                if e is not None: est[k] = e
                else: still += 1
        if exact or est: fill[code] = {'exact': exact, 'estimated': est}; n_exact += len(exact); n_est += len(est)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/fill-micros.py — do not edit by hand.\n')
        f.write('// Source: Table Ciqual 2025 (ANSES), Licence Ouverte Etalab 2.0. « exact » = same food in Ciqual;\n')
        f.write('// « estimated » = median of similar foods (same Ciqual group), flagged as an estimate in the app.\n')
        f.write("import type { Nutrients } from '../types';\n\n")
        f.write('export const CIQUAL_FILL: Record<number, { exact: Partial<Nutrients>; estimated: Partial<Nutrients> }> = ')
        f.write(json.dumps(fill, separators=(',', ':')) + ';\n')
    print(f'foods completed: {len(fill)}  official values added: {n_exact}  estimates added: {n_est}  still missing: {still}')
    reb = fill.get(12045); print('reblochon:', reb and sorted(reb['exact']), reb and sorted(reb['estimated']))

main()
