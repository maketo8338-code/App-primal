"""Samples the logo shape into particle positions for the launch animation.

Reads assets/icon.png (same unmixing as make-logos.py) and writes
src/intro/logoPoints.ts: [x, y, kind, size] with x, y in 0..1 over the logo
square, kind 0 = white (figure, text) and 1 = accent (sun, DNA rungs).

    python3 tools/make-intro-points.py
"""
import importlib.util
import random
import numpy as np
from PIL import Image

spec = importlib.util.spec_from_file_location('logos', 'tools/make-logos.py')
logos = importlib.util.module_from_spec(spec); spec.loader.exec_module(logos)

random.seed(7)
masks = {k: np.asarray(m.resize((256, 256), Image.LANCZOS), float) / 255 for k, m in logos.build_masks().items()}
H, W = masks['white'].shape
STEP = 4  # sampling grid in source pixels (256 px logo)
points = []
for y in range(0, H, STEP):
    for x in range(0, W, STEP):
        jx = min(W - 1, x + random.randint(0, STEP - 1)); jy = min(H - 1, y + random.randint(0, STEP - 1))
        w = masks['white'][jy, jx]; a = max(masks['sun'][jy, jx], masks['rungs'][jy, jx])
        if max(w, a) < 0.55:
            continue
        kind = 1 if a > w else 0
        size = round(random.uniform(1.6, 3.4), 2)
        points.append((round(jx / W, 4), round(jy / H, 4), kind, size))

with open('src/intro/logoPoints.ts', 'w') as f:
    f.write('// Generated by tools/make-intro-points.py — do not edit by hand.\n')
    f.write('// [x, y, kind, size]: x, y in 0..1 over the logo; kind 0 = white, 1 = accent colour.\n')
    f.write('export const LOGO_POINTS: ReadonlyArray<readonly [number, number, number, number]> = [\n')
    for p in points:
        f.write(f'  [{p[0]}, {p[1]}, {p[2]}, {p[3]}],\n')
    f.write('];\n')
print(len(points), 'points')
